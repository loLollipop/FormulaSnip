from __future__ import annotations

import hashlib
import json
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
BENCHMARK_DIR = ROOT / "benchmarks"

SAMPLES = (
    {
        "id": "synthetic_hyperbola",
        "expected": r"\frac{x^2}{a^2}-\frac{y^2}{b^2}=1",
    },
    {
        "id": "synthetic_integral",
        "expected": r"\int_0^\infty e^{-x^2}\,dx=\frac{\sqrt{\pi}}{2}",
    },
)


def main() -> None:
    assets = BENCHMARK_DIR / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    manifest_samples: list[dict[str, str]] = []
    for sample in SAMPLES:
        path = assets / f"{sample['id']}.png"
        _render(path, sample["expected"])
        manifest_samples.append(
            {
                "id": sample["id"],
                "path": f"assets/{path.name}",
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "license": "CC0-1.0",
                "source": "Synthetic image generated by scripts/generate_benchmark_assets.py",
                "expected": sample["expected"],
            }
        )
    manifest = {"schema_version": 1, "samples": manifest_samples}
    (BENCHMARK_DIR / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def _render(path: Path, latex: str) -> None:
    """Render the ground-truth expression itself, not a plain-text approximation."""

    from matplotlib.mathtext import math_to_image

    buffer = BytesIO()
    math_to_image(f"${latex}$", buffer, dpi=180, format="png", color="black")
    rendered = Image.open(buffer).convert("RGBA")
    white = Image.new("RGBA", rendered.size, "white")
    white.alpha_composite(rendered)
    image = ImageOps.expand(white.convert("RGB"), border=16, fill="white")
    image.save(path, format="PNG", optimize=False)


if __name__ == "__main__":
    main()
